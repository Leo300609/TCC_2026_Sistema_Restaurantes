CREATE TABLE cidade (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(200) NOT NULL,
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  ESTADO_ID integer NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE (NOME,ESTADO_ID)
);

CREATE TABLE cliente (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(255) NOT NULL,
  DOCUMENTO varchar(18) NOT NULL,
  ENDERECO varchar(400) NOT NULL,
  ENDERECO_NUMERO varchar(20) NOT NULL,
  TELEFONE varchar(15) NOT NULL,
  CONTATO varchar(255) DEFAULT NULL,
  CIDADE_ID integer NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  PRIMARY KEY (ID),
  UNIQUE (DOCUMENTO)
);

CREATE TABLE compra (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  FORNECEDOR_ID integer NOT NULL,
  FUNCIONARIO_ID integer NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  STATUS varchar(20) DEFAULT 'EM_ABERTO',
  NUMERO_NF varchar(30) DEFAULT NULL,
  OBSERVACAO varchar(255) DEFAULT NULL,
  PRIMARY KEY (ID)
);

CREATE TABLE compra_item (
  COMPRA_ID integer NOT NULL,
  PRODUTO_ID integer NOT NULL,
  QUANTIDADE integer NOT NULL DEFAULT 1,
  PRECO_UNITARIO numeric(10,2) NOT NULL DEFAULT 0.00,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  STATUS varchar(20) DEFAULT 'EM_ABERTO',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (COMPRA_ID,PRODUTO_ID)
);

CREATE TABLE configuracao (
  USUARIO_ID integer NOT NULL DEFAULT 0,
  CHAVE varchar(60) NOT NULL,
  VALOR varchar(255) NOT NULL DEFAULT '',
  PRIMARY KEY (USUARIO_ID,CHAVE)
);

CREATE TABLE conta_pagar (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  COMPRA_ID integer NOT NULL,
  PARCELA_QUANTIDADE integer NOT NULL DEFAULT 1,
  PARCELA_NUMERO integer NOT NULL DEFAULT 1,
  DATA_VENCIMENTO date NOT NULL,
  DATA_PAGAMENTO date DEFAULT NULL,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  STATUS varchar(20) DEFAULT 'PENDENTE',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE conta_receber (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  VENDA_ID integer NOT NULL,
  PARCELA_QUANTIDADE integer NOT NULL DEFAULT 1,
  PARCELA_NUMERO integer NOT NULL DEFAULT 1,
  DATA_VENCIMENTO date NOT NULL,
  DATA_PAGAMENTO date DEFAULT NULL,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  STATUS varchar(20) DEFAULT 'PENDENTE',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE convites_equipe (
  id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  id_empresa integer NOT NULL DEFAULT 1,
  codigo varchar(20) NOT NULL,
  cargo varchar(50) NOT NULL,
  nivel_acesso integer NOT NULL DEFAULT 1,
  status varchar(20) NOT NULL DEFAULT 'pendente',
  data_criacao timestamp NOT NULL DEFAULT now(),
  nivel_sistema varchar(20) NOT NULL DEFAULT 'FUNCIONARIO',
  expira_em timestamp DEFAULT NULL,
  criado_por integer DEFAULT NULL,
  usado_por integer DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE (codigo)
);

CREATE TABLE empresa (
  ID smallint NOT NULL DEFAULT 1,
  NOME_FANTASIA varchar(150) NOT NULL DEFAULT '',
  RAZAO_SOCIAL varchar(200) NOT NULL DEFAULT '',
  CNPJ varchar(18) NOT NULL DEFAULT '',
  TELEFONE varchar(20) NOT NULL DEFAULT '',
  EMAIL varchar(255) NOT NULL DEFAULT '',
  ENDERECO varchar(255) NOT NULL DEFAULT '',
  ENDERECO_NUMERO varchar(20) NOT NULL DEFAULT '',
  ESTADO char(2) NOT NULL DEFAULT 'SP',
  CIDADE varchar(200) NOT NULL DEFAULT '',
  DATA_ATUALIZACAO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE empresa_horario (
  DIA_SEMANA smallint NOT NULL,
  ABERTO smallint NOT NULL DEFAULT 1,
  ABRE time NOT NULL DEFAULT '18:00:00',
  FECHA time NOT NULL DEFAULT '23:00:00',
  PRIMARY KEY (DIA_SEMANA)
);

CREATE TABLE estado (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(200) NOT NULL,
  SIGLA char(2) NOT NULL,
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID),
  UNIQUE (NOME),
  UNIQUE (SIGLA)
);

CREATE TABLE ficha_tecnica (
  PRODUTO_ID integer NOT NULL,
  INSUMO_ID integer NOT NULL,
  QUANTIDADE integer NOT NULL DEFAULT 1,
  PRIMARY KEY (PRODUTO_ID,INSUMO_ID)
);

CREATE TABLE fornecedor (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(255) NOT NULL,
  DOCUMENTO varchar(18) NOT NULL,
  ENDERECO varchar(255) NOT NULL,
  ENDERECO_NUMERO varchar(20) NOT NULL,
  TELEFONE varchar(15) NOT NULL,
  CONTATO varchar(255) DEFAULT NULL,
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  CIDADE_ID integer NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  EMAIL varchar(255) DEFAULT NULL,
  PRIMARY KEY (ID),
  UNIQUE (DOCUMENTO)
);

CREATE TABLE fornecedor_produto (
  FORNECEDOR_ID integer NOT NULL,
  PRODUTO_ID integer NOT NULL,
  PRECO_FORNECEDOR numeric(10,2) NOT NULL DEFAULT 0.00,
  PRAZO_ENTREGA_DIAS integer DEFAULT 0,
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  PRIMARY KEY (FORNECEDOR_ID,PRODUTO_ID)
);

CREATE TABLE log_atividade (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  USUARIO_ID integer DEFAULT NULL,
  USUARIO_NOME varchar(255) NOT NULL DEFAULT '',
  MODULO varchar(40) NOT NULL,
  ACAO varchar(40) NOT NULL DEFAULT '',
  DESCRICAO varchar(500) NOT NULL,
  IP varchar(45) NOT NULL DEFAULT '',
  DATA timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE login_tentativa (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  EMAIL varchar(255) NOT NULL,
  IP varchar(45) NOT NULL,
  SUCESSO smallint NOT NULL DEFAULT 0,
  DATA timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE mesa (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NUMERO varchar(20) NOT NULL,
  LUGARES smallint NOT NULL DEFAULT 4,
  AREA varchar(50) NOT NULL DEFAULT 'Salão',
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID),
  UNIQUE (NUMERO)
);

CREATE TABLE movimentacao_caixa (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  TIPO varchar(20) NOT NULL,
  DESCRICAO varchar(255) NOT NULL,
  CATEGORIA varchar(100) NOT NULL DEFAULT 'Geral',
  VALOR numeric(10,2) NOT NULL,
  DATA_MOVIMENTACAO date NOT NULL,
  DATA_PAGAMENTO date DEFAULT NULL,
  STATUS varchar(20) NOT NULL DEFAULT 'PENDENTE',
  USUARIO_ID integer NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (ID)
);

CREATE TABLE movimentacao_estoque (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  PRODUTO_ID integer NOT NULL,
  USUARIO_ID integer NOT NULL,
  TIPO varchar(20) NOT NULL,
  QUANTIDADE integer NOT NULL,
  DATA_MOVIMENTACAO timestamp NOT NULL DEFAULT now(),
  OBSERVACAO varchar(255) DEFAULT NULL,
  PRIMARY KEY (ID)
);

CREATE TABLE produto (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(200) NOT NULL,
  DESCRICAO varchar(255) NOT NULL,
  PRECO_UNITARIO numeric(10,2) NOT NULL DEFAULT 0.00,
  ESTOQUE integer NOT NULL DEFAULT 0,
  ESTOQUE_MINIMO integer NOT NULL DEFAULT 0,
  DATA_VALIDADE date DEFAULT NULL,
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  CODIGO_BARRAS varchar(14) DEFAULT NULL,
  NCM varchar(8) DEFAULT NULL,
  UNIDADE_MEDIDA varchar(6) NOT NULL DEFAULT 'UN',
  CATEGORIA_ID integer NOT NULL,
  CONTROLA_ESTOQUE smallint NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  UNIQUE (NOME),
  UNIQUE (CODIGO_BARRAS)
);

CREATE TABLE produto_categoria (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(200) NOT NULL,
  DESCRICAO varchar(255) NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  STATUS varchar(20) NOT NULL DEFAULT 'ATIVO',
  TIPO varchar(20) NOT NULL DEFAULT 'CARDAPIO',
  PRIMARY KEY (ID),
  UNIQUE (NOME)
);

CREATE TABLE usuarios (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NOME varchar(255) NOT NULL,
  EMAIL varchar(255) NOT NULL,
  SENHA varchar(255) NOT NULL,
  NIVEL varchar(20) NOT NULL DEFAULT 'FUNCIONARIO',
  CARGO varchar(50) DEFAULT 'FUNCIONARIO',
  DATA_CADASTRO timestamp DEFAULT now(),
  ULTIMO_LOGIN timestamp DEFAULT NULL,
  ATIVO varchar(20) DEFAULT 'ATIVO',
  ULTIMO_ACESSO timestamp DEFAULT NULL,
  PRIMARY KEY (ID),
  UNIQUE (EMAIL)
);

CREATE TABLE venda (
  ID integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  CLIENTE_ID integer DEFAULT NULL,
  FUNCIONARIO_ID integer NOT NULL,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  FORMA_PAGAMENTO varchar(20) NOT NULL,
  STATUS varchar(20) DEFAULT 'EM_ABERTO',
  TIPO_PEDIDO varchar(20) NOT NULL DEFAULT 'BALCAO',
  MESA varchar(20) DEFAULT NULL,
  ETAPA varchar(20) NOT NULL DEFAULT 'NOVO',
  DATA_ETAPA timestamp NOT NULL DEFAULT now(),
  OBSERVACAO varchar(255) DEFAULT NULL,
  VALOR_RECEBIDO numeric(10,2) DEFAULT NULL,
  ESTOQUE_BAIXADO smallint NOT NULL DEFAULT 0,
  PRIMARY KEY (ID)
);

CREATE TABLE venda_item (
  VENDA_ID integer NOT NULL,
  PRODUTO_ID integer NOT NULL,
  QUANTIDADE integer NOT NULL DEFAULT 1,
  PRECO_UNITARIO numeric(10,2) NOT NULL DEFAULT 0.00,
  VALOR numeric(10,2) NOT NULL DEFAULT 0.00,
  DESCONTO numeric(10,2) NOT NULL DEFAULT 0.00,
  TOTAL numeric(10,2) NOT NULL DEFAULT 0.00,
  DATA_CADASTRO timestamp NOT NULL DEFAULT now(),
  STATUS varchar(20) DEFAULT 'EM_ABERTO',
  OBSERVACAO varchar(255) DEFAULT NULL,
  PRIMARY KEY (VENDA_ID,PRODUTO_ID)
);

