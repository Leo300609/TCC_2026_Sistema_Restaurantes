USE TCC;

-- Perfil da empresa: o sistema atual fixa id_empresa=1 no login.
CREATE TABLE IF NOT EXISTS EMPRESA (
    ID INT NOT NULL PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    DOCUMENTO VARCHAR(18) NULL,
    TELEFONE VARCHAR(15) NULL,
    EMAIL VARCHAR(255) NULL,
    ENDERECO VARCHAR(400) NULL,
    ENDERECO_NUMERO VARCHAR(20) NULL,
    CIDADE_ID INT NOT NULL,
    DATA_ATUALIZACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_EMPRESA_CIDADE FOREIGN KEY (CIDADE_ID) REFERENCES CIDADE(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Preferências operacionais simples em formato chave/valor.
CREATE TABLE IF NOT EXISTS CONFIGURACAO_SISTEMA (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CHAVE VARCHAR(80) NOT NULL UNIQUE,
    VALOR VARCHAR(255) NOT NULL DEFAULT '',
    TIPO VARCHAR(24) NOT NULL DEFAULT 'string',
    DATA_ATUALIZACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

